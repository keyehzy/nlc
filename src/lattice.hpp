// Lattices, their point groups, and connected site clusters modulo symmetry.
//
// Sites are integer pairs (a, b) at a*e1 + b*e2.  The square lattice uses
// e1 = (1, 0), e2 = (0, 1); the triangular lattice e1 = (1, 0),
// e2 = (1/2, sqrt3/2).  The honeycomb lattice is the triangular lattice
// without the points a - b = 0 (mod 3), so it has two sites per unit cell.
//
// These lattices also serve as lattices of building blocks: the triangles of
// the kagome lattice sit on the sites of a honeycomb lattice and the
// up-pointing triangles of the triangular lattice on the sites of a
// triangular lattice, two blocks sharing a corner exactly when their sites
// are neighbours.
#pragma once

#include <compare>
#include <optional>
#include <string>
#include <utility>
#include <vector>

namespace nlc {

struct Site {
  int a = 0;
  int b = 0;
  auto operator<=>(const Site&) const = default;
};

inline Site operator+(Site s, Site t) { return {s.a + t.a, s.b + t.b}; }
inline Site operator-(Site s, Site t) { return {s.a - t.a, s.b - t.b}; }

// Integer 2x2 matrix acting on (a, b).
struct PointOp {
  int m0, m1, m2, m3;
  Site operator()(Site s) const { return {m0 * s.a + m1 * s.b, m2 * s.a + m3 * s.b}; }
  bool operator==(const PointOp&) const = default;
};

struct Lattice {
  std::string name;
  std::vector<Site> dirs;      // positive bond directions, between two sites
  std::vector<PointOp> group;  // point group about the origin, identity first
  // Translations: the lattice generated by (cell.p, 0) and (cell.q, cell.r),
  // in Hermite normal form (0 <= q < p).  residue() numbers the p * r cosets
  // of the translations; anchors[residue] is the site of that coset to which
  // a cluster's smallest site is translated, or empty where the coset holds
  // no sites.  Bravais lattices have p = r = 1.
  struct Cell {
    int p = 1, q = 0, r = 1;
  } cell;
  std::vector<std::optional<Site>> anchors{Site{}};

  int residue(Site s) const;
  bool is_site(Site s) const { return anchors[residue(s)].has_value(); }
  int cell_sites() const;
  std::vector<Site> neighbours(Site s) const;
};

const Lattice& square_lattice();
const Lattice& triangular_lattice();
const Lattice& honeycomb_lattice();
// The triangular lattice with the C3v point group of an up-pointing
// triangle: the symmetry of the up-triangles as blocks, since the D6
// rotation by 60 degrees exchanges up- and down-pointing triangles.
const Lattice& up_triangle_lattice();
// A copy of `lat` with the trivial point group, for cross-checks.
Lattice without_point_group(const Lattice& lat);

using Bond = std::pair<Site, Site>;

// Every lattice bond with both endpoints in `sites`, each as (smaller,
// larger) and the list sorted.
std::vector<Bond> induced_bonds(const Lattice& lat, const std::vector<Site>& sites);

// Canonical representative: translated so its smallest site is the anchor of
// its residue, minimised over the point group, sorted.
std::vector<Site> canonical_sites(const Lattice& lat, const std::vector<Site>& sites);

// Number of distinct translation classes in the point-group orbit, i.e. the
// embeddings of the cluster per unit cell.
int site_orbit_size(const Lattice& lat, const std::vector<Site>& sites);

// reps[s] lists the canonical connected clusters of s sites, s = 1..smax.
// Size 1 holds one site of each sublattice inequivalent under the point
// group; each larger size is grown from the previous one by adding a
// neighbouring site.  The order of discovery is deterministic.
std::vector<std::vector<std::vector<Site>>> enumerate_site_clusters(const Lattice& lat, int smax);

}  // namespace nlc
