Spectrum spectrum(int n, const std::vector<Edge>& bonds, const Model& m) {
  if (n < 1 || n > 24) throw std::invalid_argument("cluster size out of range for exact diagonalisation");
  std::vector<std::pair<double, double>> levels;
  std::size_t largest = 0;

  if (m.jperp == 0.0 && m.hx == 0.0) {
    levels.reserve(std::size_t{1} << n);
    for (State s = 0; s < (State{1} << n); ++s) levels.emplace_back(diagonal_energy(s, n, bonds, m), 1.0);
    Spectrum out = merge(levels);
    out.largest_block = 1;
    return out;
  }

  Group grp;
  grp.n = n;
  grp.pairs = twin_pairs(n, bonds);
  if (grp.pairs.size() > 12) grp.pairs.resize(12);
  Orbits orb;

  auto run_sector = [&](const std::vector<State>& sector, bool flip, double weight) {
    grp.flip = flip;
    build_orbits(grp, sector, orb);
    for (unsigned chi = 0; chi < static_cast<unsigned>(grp.order()); ++chi) {
      diagonalise_block(n, bonds, m, grp, orb, chi, weight, levels, largest);
    }
  };

  if (m.hx != 0.0) {
    std::vector<State> all(std::size_t{1} << n);
    for (State s = 0; s < all.size(); ++s) all[s] = s;
    run_sector(all, m.hz == 0.0, 1.0);
  } else {
    for (int up = 0; up <= n; ++up) {
      const bool mirrored = m.hz == 0.0 && 2 * up != n;
      if (mirrored && 2 * up > n) continue;
      run_sector(states_with_popcount(n, up), m.hz == 0.0 && 2 * up == n, mirrored ? 2.0 : 1.0);
    }
  }
  Spectrum out = merge(levels);
  out.largest_block = largest;
  return out;
}

Spectrum spectrum_without_symmetries(int n, const std::vector<Edge>& bonds, const Model& m) {
  if (n < 1 || n > 12) throw std::invalid_argument("cluster too large for the unsymmetrised check");
  const int dim = 1 << n;
  std::vector<double> h(static_cast<std::size_t>(dim) * dim, 0.0);
  for (State s = 0; s < static_cast<State>(dim); ++s) {
    h[s * dim + s] = diagonal_energy(s, n, bonds, m);
    for (auto [i, j] : bonds) {
      if ((s >> i ^ s >> j) & 1u) h[s * dim + (s ^ ((1u << i) | (1u << j)))] += 0.5 * m.jperp;
    }
    for (int i = 0; i < n; ++i) h[s * dim + (s ^ (1u << i))] += -0.5 * m.hx;
  }
  std::vector<std::pair<double, double>> levels;
  for (double e : eigenvalues(h, dim)) levels.emplace_back(e, 1.0);
  Spectrum out = merge(levels);
  out.largest_block = dim;
  return out;
}

