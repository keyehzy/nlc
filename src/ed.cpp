using State = std::uint32_t;

class MemoryBudget {
public:
  void set(std::size_t bytes) {
    std::lock_guard lock(mutex_);
    total_ = bytes;
  }

  void acquire(std::size_t bytes) {
    std::unique_lock lock(mutex_);
    cv_.wait(lock, [&] { return used_ == 0 || used_ + bytes <= total_; });
    used_ += bytes;
  }

  void release(std::size_t bytes) {
    {
      std::lock_guard lock(mutex_);
      used_ -= bytes;
    }
    cv_.notify_all();
  }

private:
  std::mutex mutex_;
  std::condition_variable cv_;
  std::size_t total_ = std::size_t{8} << 30;
  std::size_t used_ = 0;
};

MemoryBudget& budget() {
  static MemoryBudget b;
  return b;
}

class Reservation {
public:
  explicit Reservation(std::size_t bytes) : bytes_(bytes) { budget().acquire(bytes_); }
  ~Reservation() { budget().release(bytes_); }
  Reservation(const Reservation&) = delete;
  Reservation& operator=(const Reservation&) = delete;

private:
  std::size_t bytes_;
};

// Eigenvalues of the symmetric dim x dim column-major matrix `a` (upper
// triangle referenced), destroying it.  Large blocks use the two-stage
// reduction (dense to band to tridiagonal): the one-stage dsytrd streams the
// whole matrix through memory once per column, which saturates the memory
// bandwidth as soon as several blocks are diagonalised concurrently.
std::vector<double> eigenvalues(std::vector<double>& a, int dim) {
  std::vector<double> w(dim);
  if (dim == 0) return w;
  if (dim == 1) {
    w[0] = a[0];
    return w;
  }
  const char jobz = 'N', uplo = 'U';
  const lapack_int n = dim, lda = dim;
  lapack_int info = 0, lwork = -1, liwork = -1, iwork_query = 0;
  double work_query = 0;
  const auto solver = dim > 256 ? dsyevd_2stage_ : dsyevd_;
  solver(&jobz, &uplo, &n, a.data(), &lda, w.data(), &work_query, &lwork, &iwork_query, &liwork, &info);
  lwork = static_cast<lapack_int>(work_query);
  liwork = std::max<lapack_int>(iwork_query, 1);
  std::vector<double> work(lwork);
  std::vector<lapack_int> iwork(liwork);
  solver(&jobz, &uplo, &n, a.data(), &lda, w.data(), work.data(), &lwork, iwork.data(), &liwork, &info);
  if (info != 0) throw std::runtime_error("dsyevd failed with info " + std::to_string(info));
  return w;
}

double diagonal_energy(State s, int n, const std::vector<Edge>& bonds, const Model& m) {
  double e = 0.0;
  for (auto [i, j] : bonds) e += ((s >> i ^ s >> j) & 1u) ? -0.25 * m.jz : 0.25 * m.jz;
  return e - m.hz * (std::popcount(s) - 0.5 * n);
}

// Merges levels that agree to rounding and sorts them.
Spectrum merge(std::vector<std::pair<double, double>>& levels) {
  std::sort(levels.begin(), levels.end());
  Spectrum out;
  for (auto [e, g] : levels) {
    if (!out.energy.empty() && std::abs(e - out.energy.back()) <= 1e-11 * std::max(1.0, std::abs(e))) {
      out.degeneracy.back() += g;
    } else {
      out.energy.push_back(e);
      out.degeneracy.push_back(g);
    }
  }
  return out;
}

// The abelian group generated by the twin swaps (bits 0..P-1 of an element)
// and, where it maps the sector to itself, the global flip (bit P).
struct Group {
  int n = 0;
  std::vector<Edge> pairs;
  bool flip = false;

  int bits() const { return static_cast<int>(pairs.size()) + (flip ? 1 : 0); }
  int order() const { return 1 << bits(); }

  State apply(unsigned g, State s) const {
    for (unsigned m = g & ((1u << pairs.size()) - 1); m; m &= m - 1) {
      auto [u, v] = pairs[__builtin_ctz(m)];
      if ((s >> u ^ s >> v) & 1u) s ^= (State{1} << u) | (State{1} << v);
    }
    if (flip && (g >> pairs.size() & 1u)) s ^= (n == 32 ? ~State{0} : (State{1} << n) - 1);
    return s;
  }
};

// Orbits of the group within one sector.  Every state of the sector maps to
// the index of its orbit's representative (the smallest state) and to a group
// element g with state = g(rep).
struct Orbits {
  std::vector<State> reps;
  std::vector<unsigned> equal_pairs;  // twin pairs with equal spins: their swaps fix the rep
  std::vector<char> flip_fixed;       // the flip times all swaps fixes the rep
  std::vector<std::int32_t> rep_of;   // over all 2^n states, -1 outside the sector
  std::vector<std::uint16_t> elem_of;
};

void build_orbits(const Group& grp, const std::vector<State>& sector, Orbits& orb) {
  const int n = grp.n;
  orb.reps.clear();
  orb.equal_pairs.clear();
  orb.flip_fixed.clear();
  orb.rep_of.assign(std::size_t{1} << n, -1);
  orb.elem_of.assign(std::size_t{1} << n, 0);
  const unsigned all_pairs = (1u << grp.pairs.size()) - 1;
  for (State s : sector) {
    if (orb.rep_of[s] >= 0) continue;
    const auto idx = static_cast<std::int32_t>(orb.reps.size());
    orb.reps.push_back(s);
    unsigned eq = 0;
    for (std::size_t p = 0; p < grp.pairs.size(); ++p) {
      auto [u, v] = grp.pairs[p];
      if (!((s >> u ^ s >> v) & 1u)) eq |= 1u << p;
    }
    orb.equal_pairs.push_back(eq);
    orb.flip_fixed.push_back(grp.flip && grp.apply(all_pairs | (1u << grp.pairs.size()), s) == s);
    for (int g = 0; g < grp.order(); ++g) {
      const State t = grp.apply(g, s);
      if (orb.rep_of[t] < 0) {
        orb.rep_of[t] = idx;
        orb.elem_of[t] = static_cast<std::uint16_t>(g);
      }
    }
  }
}

// Diagonalises the block of character `chi` (bit k set: odd under generator
// k) and appends its levels with weight `weight`.
void diagonalise_block(int n, const std::vector<Edge>& bonds, const Model& m, const Group& grp, const Orbits& orb,
                       unsigned chi, double weight, std::vector<std::pair<double, double>>& levels,
                       std::size_t& largest) {
  const unsigned all_pairs = (1u << grp.pairs.size()) - 1;
  const unsigned full = all_pairs | (grp.flip ? 1u << grp.pairs.size() : 0u);
  const std::size_t nreps = orb.reps.size();
  std::vector<std::int32_t> index(nreps, -1);
  std::vector<double> stab(nreps, 0.0);
  int dim = 0;
  for (std::size_t r = 0; r < nreps; ++r) {
    if (chi & orb.equal_pairs[r]) continue;
    if (orb.flip_fixed[r] && (std::popcount(chi & full) & 1)) continue;
    index[r] = dim++;
    stab[r] = static_cast<double>(1u << std::popcount(orb.equal_pairs[r])) * (orb.flip_fixed[r] ? 2.0 : 1.0);
  }
  if (dim == 0) return;
  largest = std::max<std::size_t>(largest, dim);

  const std::size_t bytes = static_cast<std::size_t>(dim) * dim * sizeof(double);
  Reservation hold(bytes);
  std::vector<double> h(static_cast<std::size_t>(dim) * dim, 0.0);
  auto add = [&](std::size_t col, State t, double amp, double norm) {
    const std::int32_t r = orb.rep_of[t];
    const std::int32_t row = index[r];
    if (row < 0) return;
    const double sign = (std::popcount(orb.elem_of[t] & chi) & 1) ? -1.0 : 1.0;
    h[col * dim + row] += amp * sign * std::sqrt(stab[r] / norm);
  };
  bool offdiagonal = false;
  for (std::size_t r = 0; r < nreps; ++r) {
    const std::int32_t col = index[r];
    if (col < 0) continue;
    const State s = orb.reps[r];
    h[static_cast<std::size_t>(col) * dim + col] += diagonal_energy(s, n, bonds, m);
    if (m.jperp != 0.0) {
      for (auto [i, j] : bonds) {
        if ((s >> i ^ s >> j) & 1u) {
          add(col, s ^ ((State{1} << i) | (State{1} << j)), 0.5 * m.jperp, stab[r]);
          offdiagonal = true;
        }
      }
    }
    if (m.hx != 0.0) {
      for (int i = 0; i < n; ++i) add(col, s ^ (State{1} << i), -0.5 * m.hx, stab[r]);
      offdiagonal = true;
    }
  }
  std::vector<double> w;
  if (offdiagonal) {
    w = eigenvalues(h, dim);
  } else {
    w.resize(dim);
    for (int k = 0; k < dim; ++k) w[k] = h[static_cast<std::size_t>(k) * dim + k];
  }
  for (double e : w) levels.emplace_back(e, weight);
}

std::vector<State> states_with_popcount(int n, int up) {
  std::vector<State> out;
  if (up == 0) return {0};
  // Gosper's hack enumerates the k-subsets in increasing order.
  State s = (State{1} << up) - 1;
  const std::uint64_t limit = std::uint64_t{1} << n;
  while (s < limit) {
    out.push_back(s);
    const State c = s & (~s + 1);
    const std::uint64_t r = static_cast<std::uint64_t>(s) + c;
    if (r >= limit) break;
    s = static_cast<State>((((r ^ s) >> 2) / c) | r);
  }
  return out;
}

